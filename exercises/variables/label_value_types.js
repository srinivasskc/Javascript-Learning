// Label Value Types
// typeof tells you the type of a value. Store each type label in its own variable before logging it.
// Your task: Three values are provided. Create nameType, priceType, and availableType by using typeof on the matching value. Log all three type labels.

const productName = "Notebook";
const price = 9.99;
const isAvailable = true;

// Create nameType, priceType, and availableType
const nameType = typeof(productName)
const priceType = typeof(price)
const availableType = typeof(isAvailable)

// Log all three type labels
console.log(nameType)
console.log(priceType)
console.log(availableType)
